import { ReactNode } from 'react'

interface ChipProps {
  children: ReactNode
  variant?: 'default' | 'success' | 'warning' | 'danger' | 'info'
  size?: 'sm' | 'md'
  className?: string
}

export default function Chip({ children, variant = 'default', size = 'md', className = '' }: ChipProps) {
  const variantClasses = {
    default: 'bg-accuracy-gray bg-opacity-20 text-accuracy-navy border border-accuracy-gray',
    success: 'bg-green-100 text-green-800 border border-green-300',
    warning: 'bg-yellow-100 text-yellow-800 border border-yellow-300',
    danger: 'bg-red-100 text-red-800 border border-red-300',
    info: 'bg-accuracy-light bg-opacity-30 text-accuracy-navy border border-accuracy-medium-light',
  }

  const sizeClasses = {
    sm: 'px-2 py-0.5 text-xs',
    md: 'px-3 py-1 text-sm',
  }

  return (
    <span
      className={`inline-flex items-center font-medium rounded-full ${variantClasses[variant]} ${sizeClasses[size]} ${className}`}
    >
      {children}
    </span>
  )
}
